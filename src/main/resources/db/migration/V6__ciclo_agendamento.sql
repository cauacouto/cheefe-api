-- Ciclo de vida do agendamento: status RECUSADO e EXPIRADO, eventos de notificação novos e a
-- linha do tempo de cada agendamento (só de inserção para a API).
SET search_path TO chefhome;

ALTER TABLE agendamentos DROP CONSTRAINT agendamentos_status_check;
ALTER TABLE agendamentos ADD CONSTRAINT agendamentos_status_check
    CHECK (status IN ('PENDENTE','CONFIRMADO','CANCELADO','CONCLUIDO','RECUSADO','EXPIRADO'));

ALTER TABLE notificacao DROP CONSTRAINT notificacao_evento_check;
ALTER TABLE notificacao ADD CONSTRAINT notificacao_evento_check CHECK (evento IN (
    'AGENDAMENTO_CRIADO','AGENDAMENTO_EDITADO','AGENDAMENTO_CONFIRMADO','DENUNCIA_CRIADA','CHEF_OCULTO',
    'CHEF_SUSPENSO','CHEF_REATIVADO','MENSAGEM_RECEBIDA','MENSAGEM_DENUNCIADA',
    'AGENDAMENTO_CANCELADO','AGENDAMENTO_RECUSADO','CHEF_DESISTIU','AGENDAMENTO_EXPIRADO'));

CREATE TABLE agendamento_historico (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    -- cascata: a exclusão de conta apaga os agendamentos do cliente e o histórico vai junto,
    -- sem a API precisar de DELETE nesta tabela
    agendamento_id bigint       NOT NULL,
    acao           varchar(255) NOT NULL CHECK (acao IN (
        'CRIADO','EDITADO','CONFIRMADO','CANCELADO','RECUSADO','DESISTENCIA','CONCLUIDO','EXPIRADO')),
    autor_id       uuid,
    autor_tipo     varchar(255) CHECK (autor_tipo IN ('CLIENTE','CHEFE')),
    motivo         varchar(255) CHECK (motivo IN (
        'MUDANCA_DE_PLANOS','DATA_OU_HORARIO','ENCONTREI_OUTRA_OPCAO','VALOR',
        'AGENDA_INDISPONIVEL','LOCAL_FORA_DA_AREA','NUMERO_DE_PESSOAS','IMPREVISTO','OUTRO')),
    descricao      varchar(300),
    ocorrido_em    timestamp(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_agendamento_historico_agendamento FOREIGN KEY (agendamento_id)
        REFERENCES agendamentos ON DELETE CASCADE
);

CREATE INDEX idx_agendamento_historico_agendamento ON agendamento_historico (agendamento_id, ocorrido_em);

-- só de inserção para a API: os default privileges dariam UPDATE/DELETE; aqui ficam INSERT e SELECT
DO $$
BEGIN
    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'chefhome_app') THEN
        REVOKE UPDATE, DELETE, TRUNCATE ON agendamento_historico FROM chefhome_app;
    END IF;
END
$$;
