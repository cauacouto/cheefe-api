-- Menus com preço por pessoa: o chef monta o menu com pratos seus, por etapa, e marca as ocasiões.
SET search_path TO chefhome;

CREATE TABLE menu (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY,
    chefe_id              uuid          NOT NULL,
    nome                  varchar(100)  NOT NULL,
    descricao             varchar(1000),
    preco_por_pessoa      numeric(10,2) NOT NULL,
    minimo_convidados     integer       NOT NULL,
    maximo_convidados     integer       NOT NULL,
    duracao_minutos       integer       NOT NULL,
    ingredientes_inclusos boolean       NOT NULL,
    ativo                 boolean       NOT NULL,
    criado_em             timestamp(6)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_menu_preco CHECK (preco_por_pessoa > 0),
    CONSTRAINT ck_menu_convidados CHECK (minimo_convidados BETWEEN 1 AND 50
        AND maximo_convidados BETWEEN minimo_convidados AND 50),
    CONSTRAINT ck_menu_duracao CHECK (duracao_minutos BETWEEN 60 AND 720 AND duracao_minutos % 30 = 0),
    CONSTRAINT fk_menu_chefe FOREIGN KEY (chefe_id) REFERENCES chefe ON DELETE CASCADE
);

CREATE INDEX idx_menu_chefe_ativo ON menu (chefe_id, ativo);

CREATE TABLE menu_item (
    menu_id  bigint      NOT NULL,
    prato_id integer     NOT NULL,
    etapa    varchar(16) NOT NULL CHECK (etapa IN ('COUVERT','ENTRADA','PRINCIPAL','SOBREMESA')),
    ordem    integer     NOT NULL,
    PRIMARY KEY (menu_id, prato_id),
    CONSTRAINT fk_menu_item_menu  FOREIGN KEY (menu_id)  REFERENCES menu ON DELETE CASCADE,
    CONSTRAINT fk_menu_item_prato FOREIGN KEY (prato_id) REFERENCES pratos ON DELETE CASCADE
);

CREATE TABLE menu_ocasiao (
    menu_id  bigint      NOT NULL,
    ocasiao  varchar(32) NOT NULL CHECK (ocasiao IN (
        'JANTAR_ROMANTICO','ANIVERSARIO','FAMILIA','AMIGOS','EMPRESA','CELEBRACAO','OUTRA')),
    PRIMARY KEY (menu_id, ocasiao),
    CONSTRAINT fk_menu_ocasiao_menu FOREIGN KEY (menu_id) REFERENCES menu ON DELETE CASCADE
);

CREATE INDEX idx_menu_ocasiao_ocasiao ON menu_ocasiao (ocasiao);
