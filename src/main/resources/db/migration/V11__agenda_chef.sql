-- Agenda do chef: períodos avulsos de indisponibilidade e dias fixos da semana.
SET search_path TO chefhome;

CREATE TABLE agenda_bloqueio (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    chefe_id  uuid         NOT NULL,
    inicio    timestamp(6) NOT NULL,
    fim       timestamp(6) NOT NULL,
    criado_em timestamp(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_agenda_bloqueio_periodo CHECK (fim > inicio),
    CONSTRAINT fk_agenda_bloqueio_chefe FOREIGN KEY (chefe_id) REFERENCES chefe ON DELETE CASCADE
);

CREATE INDEX idx_agenda_bloqueio_chefe_fim ON agenda_bloqueio (chefe_id, fim);

CREATE TABLE agenda_dia_fixo (
    chefe_id   uuid        NOT NULL,
    dia_semana varchar(16) NOT NULL CHECK (dia_semana IN (
        'MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY')),
    PRIMARY KEY (chefe_id, dia_semana),
    CONSTRAINT fk_agenda_dia_fixo_chefe FOREIGN KEY (chefe_id) REFERENCES chefe ON DELETE CASCADE
);
