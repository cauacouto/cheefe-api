-- Rastro das ações da moderação (quem arquivou, suspendeu, reativou ou baniu).
SET search_path TO chefhome;

CREATE TABLE acao_moderacao (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    moderador_email varchar(255) NOT NULL,
    acao            varchar(255) NOT NULL CHECK (acao IN ('ARQUIVAR_DENUNCIA','SUSPENDER_CHEF','REATIVAR_CHEF','BANIR_CHEF')),
    -- sem FKs de propósito: o rastro sobrevive à exclusão da denúncia ou do chef
    chefe_id        uuid,
    denuncia_id     bigint,
    realizada_em    timestamp(6) NOT NULL,
    PRIMARY KEY (id)
);

CREATE INDEX idx_acao_moderacao_realizada ON acao_moderacao (realizada_em DESC, id DESC);

-- só de inserção para a API: os default privileges dariam UPDATE/DELETE; aqui ficam INSERT e SELECT
DO $$
BEGIN
    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'chefhome_app') THEN
        REVOKE UPDATE, DELETE, TRUNCATE ON acao_moderacao FROM chefhome_app;
    END IF;
END
$$;
