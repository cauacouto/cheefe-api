-- Schema inicial do ChefHome, gerado a partir das entidades JPA (dialeto PostgreSQL) e revisado.
-- Roda como chefhome_migracao (dono do schema chefhome). Migrations aplicadas nunca são editadas:
-- qualquer mudança vira um novo V{n}__descricao.sql.

SET search_path TO chefhome;

-- ids Long/Integer com GenerationType.AUTO usam sequence pooled (incremento 50)
CREATE SEQUENCE agendamentos_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE endereco_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE pratos_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE usuarios (
    id        uuid         NOT NULL,
    email     varchar(255) NOT NULL UNIQUE,
    image_url varchar(255),
    nome      varchar(255) NOT NULL,
    telefone  varchar(255),
    PRIMARY KEY (id)
);

CREATE TABLE chefe (
    id                  uuid         NOT NULL,
    email               varchar(255) NOT NULL UNIQUE,
    nome                varchar(255) NOT NULL,
    password            varchar(255),
    nacionalidade       varchar(255),
    especialidade       varchar(255) CHECK (especialidade IN ('FRANCESA','ITALIANA','JAPONESA','CHINESA','ARABE','MEXICANA','INDIANA','BRASILEIRA','CONFEITARIA','CHURRASCO','FRUTOS_DO_MAR','VEGANA','FINE_DINING','PANIFICACAO')),
    anos_de_experiencia integer,
    senioridade         varchar(255) CHECK (senioridade IN ('COZINHEIRO','SOUS_CHEF','CHEF_DE_PARTIE','HEAD_CHEF','EXECUTIVE_CHEF')),
    disponivel          boolean      NOT NULL DEFAULT true,
    ativo               boolean               DEFAULT true,
    suspenso            boolean      NOT NULL DEFAULT false,
    idiomas             varchar(255),
    image_url           varchar(255),
    valor_hora          numeric(38,2),
    PRIMARY KEY (id)
);

CREATE TABLE endereco (
    id                 bigint       NOT NULL,
    user_id            uuid,
    rua                varchar(255),
    numero             varchar(255),
    bairro             varchar(255),
    cidade             varchar(255),
    estado             varchar(255),
    cep                varchar(255),
    complemento        varchar(255),
    tipo_de_residencia smallint CHECK (tipo_de_residencia BETWEEN 0 AND 1),
    PRIMARY KEY (id),
    CONSTRAINT fk_endereco_usuario FOREIGN KEY (user_id) REFERENCES usuarios
);

CREATE TABLE agendamentos (
    id                 bigint NOT NULL,
    user_id            uuid,
    endereco_id        bigint,
    quantidade_pessoas integer,
    status             smallint CHECK (status BETWEEN 0 AND 3),
    valor_total        numeric(10,2),
    data_hora_inicial  timestamp(6),
    data_hora_final    timestamp(6),
    criado_em          timestamp(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_agendamento_usuario FOREIGN KEY (user_id) REFERENCES usuarios,
    CONSTRAINT fk_agendamento_endereco FOREIGN KEY (endereco_id) REFERENCES endereco
);

-- nome da tabela de junção segue o mapeamento atual da entidade (correção do nome fica para o lote de renomeação)
CREATE TABLE agedamento_chefe (
    agendamento_id bigint NOT NULL,
    chefe_id       uuid   NOT NULL,
    CONSTRAINT fk_agendamento_chefe_agendamento FOREIGN KEY (agendamento_id) REFERENCES agendamentos,
    CONSTRAINT fk_agendamento_chefe_chefe FOREIGN KEY (chefe_id) REFERENCES chefe
);

CREATE TABLE pratos (
    id         integer NOT NULL,
    chefe_id   uuid    NOT NULL,
    nome_prato varchar(255),
    descricao  varchar(255),
    image_url  varchar(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_prato_chefe FOREIGN KEY (chefe_id) REFERENCES chefe
);

CREATE TABLE notificacao (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    destinatario_id   uuid         NOT NULL,
    destinatario_tipo varchar(255) NOT NULL CHECK (destinatario_tipo IN ('CLIENTE','CHEFE','MODERADOR')),
    evento            varchar(255) NOT NULL CHECK (evento IN ('AGENDAMENTO_CRIADO','AGENDAMENTO_EDITADO','AGENDAMENTO_CONFIRMADO','DENUNCIA_CRIADA','CHEF_OCULTO','CHEF_SUSPENSO','CHEF_REATIVADO','MENSAGEM_RECEBIDA')),
    mensagem          varchar(300) NOT NULL,
    referencia_id     varchar(64),
    lida              boolean      NOT NULL,
    criada_em         timestamp(6) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE denuncia (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    chefe_id       uuid          NOT NULL,
    cliente_id     uuid          NOT NULL,
    agendamento_id bigint        NOT NULL,
    motivo         varchar(255)  NOT NULL CHECK (motivo IN ('COMPORTAMENTO','NAO_COMPARECEU','HIGIENE','PERFIL_FALSO','OUTRO')),
    descricao      varchar(1000) NOT NULL,
    status         varchar(255)  NOT NULL CHECK (status IN ('ABERTA','ARQUIVADA','PROCEDENTE')),
    criada_em      timestamp(6)  NOT NULL,
    resolvida_em   timestamp(6),
    resolvida_por  varchar(255),
    PRIMARY KEY (id),
    CONSTRAINT fk_denuncia_chefe FOREIGN KEY (chefe_id) REFERENCES chefe,
    CONSTRAINT fk_denuncia_cliente FOREIGN KEY (cliente_id) REFERENCES usuarios,
    CONSTRAINT fk_denuncia_agendamento FOREIGN KEY (agendamento_id) REFERENCES agendamentos
);

-- índices de consulta
CREATE INDEX idx_notificacao_destinatario ON notificacao (destinatario_id, lida, criada_em);
CREATE INDEX idx_denuncia_chefe_status ON denuncia (chefe_id, status);
CREATE INDEX idx_denuncia_cliente_chefe_status ON denuncia (cliente_id, chefe_id, status);
CREATE INDEX idx_endereco_usuario ON endereco (user_id);
CREATE INDEX idx_agendamentos_usuario ON agendamentos (user_id);
CREATE INDEX idx_agedamento_chefe_chefe ON agedamento_chefe (chefe_id);
CREATE INDEX idx_pratos_chefe ON pratos (chefe_id);
