SET search_path TO chefhome;

ALTER TABLE agendamentos ADD COLUMN concluido_em timestamp(6);

ALTER TABLE usuarios ADD COLUMN soma_notas       integer NOT NULL DEFAULT 0;
ALTER TABLE usuarios ADD COLUMN total_avaliacoes integer NOT NULL DEFAULT 0;
ALTER TABLE chefe    ADD COLUMN soma_notas       integer NOT NULL DEFAULT 0;
ALTER TABLE chefe    ADD COLUMN total_avaliacoes integer NOT NULL DEFAULT 0;

CREATE TABLE avaliacao (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    agendamento_id      bigint        NOT NULL,
    autor_id            uuid          NOT NULL,
    autor_tipo          varchar(255)  NOT NULL CHECK (autor_tipo IN ('CLIENTE','CHEFE')),
    avaliado_id         uuid          NOT NULL,
    avaliado_tipo       varchar(255)  NOT NULL CHECK (avaliado_tipo IN ('CLIENTE','CHEFE')),
    nota                integer       NOT NULL CHECK (nota BETWEEN 1 AND 5),
    comentario          varchar(1000),
    comentario_original varchar(1000),
    anonimo             boolean       NOT NULL DEFAULT true,
    publicado_em        timestamp(6),
    comentario_removido boolean       NOT NULL DEFAULT false,
    resposta            varchar(1000),
    resposta_original   varchar(1000),
    respondida_em       timestamp(6),
    criada_em           timestamp(6)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_avaliacao_agendamento_autor_avaliado UNIQUE (agendamento_id, autor_id, avaliado_id),
    CONSTRAINT fk_avaliacao_agendamento FOREIGN KEY (agendamento_id) REFERENCES agendamentos ON DELETE CASCADE
);

CREATE INDEX idx_avaliacao_avaliado_publicado ON avaliacao (avaliado_id, publicado_em);

CREATE TABLE avaliacao_tag (
    avaliacao_id bigint       NOT NULL,
    tag          varchar(255) NOT NULL CHECK (tag IN (
        'PONTUAL','COMIDA_EXCELENTE','SIMPATICO','COZINHA_LIMPA','APRESENTACAO_CAPRICHADA','ATRASOU',
        'COMIDA_ABAIXO_DO_ESPERADO','DEIXOU_SUJEIRA','NAO_CUMPRIU_O_COMBINADO',
        'EDUCADO','RECEPTIVO','COZINHA_ORGANIZADA','PAGOU_COMO_COMBINADO','MUDOU_EM_CIMA_DA_HORA',
        'DEMOROU_PARA_RECEBER','COZINHA_SEM_CONDICOES','FALTA_DE_EDUCACAO')),
    CONSTRAINT fk_avaliacao_tag_avaliacao FOREIGN KEY (avaliacao_id) REFERENCES avaliacao ON DELETE CASCADE
);

CREATE INDEX idx_avaliacao_tag_avaliacao ON avaliacao_tag (avaliacao_id);

CREATE TABLE denuncia_avaliacao (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    avaliacao_id     bigint        NOT NULL,
    denunciante_id   uuid          NOT NULL,
    denunciante_tipo varchar(255)  NOT NULL CHECK (denunciante_tipo IN ('CLIENTE','CHEFE','MODERADOR')),
    autor_id         uuid          NOT NULL,
    autor_tipo       varchar(255)  NOT NULL CHECK (autor_tipo IN ('CLIENTE','CHEFE','MODERADOR')),
    texto_denunciado varchar(1000) NOT NULL,
    motivo           varchar(255)  NOT NULL CHECK (motivo IN ('OFENSIVA','DADOS_PESSOAIS','FALSA','SPAM','OUTRO')),
    descricao        varchar(1000),
    status           varchar(255)  NOT NULL CHECK (status IN ('ABERTA','ARQUIVADA','PROCEDENTE')),
    criada_em        timestamp(6)  NOT NULL,
    resolvida_em     timestamp(6),
    resolvida_por    varchar(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_denuncia_avaliacao_denunciante UNIQUE (avaliacao_id, denunciante_id),
    CONSTRAINT fk_denuncia_avaliacao_avaliacao FOREIGN KEY (avaliacao_id) REFERENCES avaliacao ON DELETE CASCADE
);

CREATE INDEX idx_denuncia_avaliacao_status ON denuncia_avaliacao (status, criada_em);

ALTER TABLE acao_moderacao DROP CONSTRAINT acao_moderacao_acao_check;
ALTER TABLE acao_moderacao ADD CONSTRAINT acao_moderacao_acao_check CHECK (acao IN (
    'ARQUIVAR_DENUNCIA','SUSPENDER_CHEF','REATIVAR_CHEF','BANIR_CHEF',
    'ARQUIVAR_DENUNCIA_MENSAGEM','REMOVER_MENSAGEM','CONFIRMAR_BLOQUEIO','REVERTER_BLOQUEIO',
    'ARQUIVAR_DENUNCIA_AVALIACAO','REMOVER_COMENTARIO_AVALIACAO'));

ALTER TABLE notificacao DROP CONSTRAINT notificacao_evento_check;
ALTER TABLE notificacao ADD CONSTRAINT notificacao_evento_check CHECK (evento IN (
    'AGENDAMENTO_CRIADO','AGENDAMENTO_EDITADO','AGENDAMENTO_CONFIRMADO','DENUNCIA_CRIADA','CHEF_OCULTO',
    'CHEF_SUSPENSO','CHEF_REATIVADO','MENSAGEM_RECEBIDA','MENSAGEM_DENUNCIADA',
    'AGENDAMENTO_CANCELADO','AGENDAMENTO_RECUSADO','CHEF_DESISTIU','AGENDAMENTO_EXPIRADO',
    'CONTA_BLOQUEADA','AVALIACAO_RECEBIDA','AVALIACAO_RESPONDIDA','AVALIACAO_DENUNCIADA'));
