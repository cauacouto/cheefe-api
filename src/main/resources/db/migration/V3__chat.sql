-- Chat entre cliente e chef: conversas, mensagens e denúncias de mensagem.
-- Diferente da auditoria, a API precisa de UPDATE aqui (editar, apagar, marcar lida, status da denúncia),
-- então os default privileges do setup (só DML) bastam.
SET search_path TO chefhome;

CREATE TABLE conversa (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    cliente_id         uuid         NOT NULL,
    chefe_id           uuid         NOT NULL,
    criada_em          timestamp(6) NOT NULL,
    ultima_mensagem_em timestamp(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conversa_cliente_chefe UNIQUE (cliente_id, chefe_id),
    CONSTRAINT fk_conversa_cliente FOREIGN KEY (cliente_id) REFERENCES usuarios,
    CONSTRAINT fk_conversa_chefe FOREIGN KEY (chefe_id) REFERENCES chefe
);

CREATE TABLE mensagem (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,
    conversa_id            bigint        NOT NULL,
    remetente_id           uuid          NOT NULL,
    remetente_tipo         varchar(255)  NOT NULL CHECK (remetente_tipo IN ('CLIENTE','CHEFE','MODERADOR')),
    texto                  varchar(2000) NOT NULL,
    enviada_em             timestamp(6)  NOT NULL,
    lida_em                timestamp(6),
    editada_em             timestamp(6),
    apagada_em             timestamp(6),
    removida_por_moderacao boolean       NOT NULL DEFAULT false,
    PRIMARY KEY (id),
    CONSTRAINT fk_mensagem_conversa FOREIGN KEY (conversa_id) REFERENCES conversa
);

CREATE TABLE denuncia_mensagem (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    mensagem_id      bigint        NOT NULL,
    denunciante_id   uuid          NOT NULL,
    denunciante_tipo varchar(255)  NOT NULL CHECK (denunciante_tipo IN ('CLIENTE','CHEFE','MODERADOR')),
    autor_id         uuid          NOT NULL,
    autor_tipo       varchar(255)  NOT NULL CHECK (autor_tipo IN ('CLIENTE','CHEFE','MODERADOR')),
    texto_denunciado varchar(2000) NOT NULL,
    motivo           varchar(255)  NOT NULL CHECK (motivo IN ('OFENSIVA','ASSEDIO','SPAM','GOLPE','CONTEUDO_IMPROPRIO','OUTRO')),
    descricao        varchar(1000),
    status           varchar(255)  NOT NULL CHECK (status IN ('ABERTA','ARQUIVADA','PROCEDENTE')),
    criada_em        timestamp(6)  NOT NULL,
    resolvida_em     timestamp(6),
    resolvida_por    varchar(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_denuncia_mensagem_denunciante UNIQUE (mensagem_id, denunciante_id),
    CONSTRAINT fk_denuncia_mensagem_mensagem FOREIGN KEY (mensagem_id) REFERENCES mensagem
);

CREATE INDEX idx_mensagem_conversa ON mensagem (conversa_id, id);
CREATE INDEX idx_denuncia_mensagem_status ON denuncia_mensagem (status, criada_em);
CREATE INDEX idx_conversa_chefe ON conversa (chefe_id);

-- enums que ganharam valores (o teste de CHECKs compara com os enums Java)
ALTER TABLE notificacao DROP CONSTRAINT notificacao_evento_check;
ALTER TABLE notificacao ADD CONSTRAINT notificacao_evento_check CHECK (evento IN (
    'AGENDAMENTO_CRIADO','AGENDAMENTO_EDITADO','AGENDAMENTO_CONFIRMADO','DENUNCIA_CRIADA','CHEF_OCULTO',
    'CHEF_SUSPENSO','CHEF_REATIVADO','MENSAGEM_RECEBIDA','MENSAGEM_DENUNCIADA'));

ALTER TABLE acao_moderacao DROP CONSTRAINT acao_moderacao_acao_check;
ALTER TABLE acao_moderacao ADD CONSTRAINT acao_moderacao_acao_check CHECK (acao IN (
    'ARQUIVAR_DENUNCIA','SUSPENDER_CHEF','REATIVAR_CHEF','BANIR_CHEF',
    'ARQUIVAR_DENUNCIA_MENSAGEM','REMOVER_MENSAGEM'));
